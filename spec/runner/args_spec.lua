local Args = require("wowtest.args")

describe("wowtest args", function()
	it("collects path filters, names and tags", function()
		local options = Args.Parse({ "units", "-t", "full health", "--test", "bar", "--tag", "#shields", "units/" })
		assert.same({ "units", "units/" }, options.paths)
		assert.same({ "full health", "bar" }, options.names)
		assert.same({ "shields" }, options.tags)
	end)

	it("reads -j with and without a count", function()
		assert.equals(0, Args.Parse({ "-j" }).jobs)
		assert.equals(4, Args.Parse({ "-j", "4" }).jobs)
		assert.equals(0, Args.Parse({ "--jobs", "units" }).jobs)
		assert.same({ "units" }, Args.Parse({ "--jobs", "units" }).paths)
	end)

	it("reads --times, --config, --child and --help", function()
		local options = Args.Parse({ "--times", "--config", "x.lua", "--child", "out.lua", "a_spec.lua", "-h" })
		assert.is_true(options.times)
		assert.is_true(options.help)
		assert.equals("x.lua", options.config)
		assert.equals("out.lua", options.child)
	end)

	it("rejects unknown options and missing values", function()
		assert.has_error(function() Args.Parse({ "--nope" }) end)
		assert.has_error(function() Args.Parse({ "-t" }) end)
		assert.has_error(function() Args.Parse({ "--config" }) end)
	end)
end)
